"""Build the in-host probe with its confidential identity (design.md §5.2, probe-protocol.md §5).

`[CommandMethod]` and `[LispFunction]` names must be compile-time constants, so the names from
`config/probe_identity.yaml` are written to `Generated/Identity.g.cs` and the assembly is built under the
configured neutral name. The config model restricts every name to a strict pattern before it reaches C#.
"""

from pathlib import Path

from mta.adapters.autocad.build import BuildError, build_for, output_dir
from mta.config import REPO_ROOT, MtaConfig
from mta.config.models import HostProbeIdentity

PROJECT = REPO_ROOT / "dotnet" / "probes" / "AcProbe"


class ProbeBuildError(Exception):
    """The probe could not be built (an MTA problem: dynamic checks become ERROR)."""


def render_identity(identity: HostProbeIdentity) -> str:
    c = identity.commands
    constants = {
        "Group": identity.assembly_name,
        "RunDirEnv": identity.run_dir_env,
        "PlanFile": identity.plan_file,
        "EventsFile": identity.events_file,
        "LispFunction": identity.lisp_function,
        "Load": c.load,
        "Enumerate": c.enumerate,
        "Mark": c.mark,
        "Assert": c.assert_,
        "End": c.end,
    }
    lines = [
        "// <auto-generated> by `mta probe build` from config/probe_identity.yaml. Do not edit or commit.",
        "namespace Wa;",
        "",
        "internal static class Identity",
        "{",
        *(f'    public const string {name} = "{value}";' for name, value in constants.items()),
        "",
        "    private static readonly HashSet<string> Own =",
        "        new(StringComparer.OrdinalIgnoreCase) { Load, Enumerate, Mark, Assert, End };",
        "",
        "    public static bool IsOwnCommand(string name) => Own.Contains(name.TrimStart('_'));",
        "}",
        "",
    ]
    return "\n".join(lines)


def probe_dll(cfg: MtaConfig, year: int = 2026) -> Path:
    """The probe built for `year`'s API major (one build per major, see build.py)."""
    return output_dir(PROJECT, cfg, year) / f"{cfg.probe_identity.autocad.assembly_name}.dll"


def build_probe(cfg: MtaConfig, *, acad_version: int = 2026) -> Path:
    """Generate the identity and build for one AutoCAD version. Needs that AutoCAD installed."""
    identity = cfg.probe_identity.autocad
    generated = PROJECT / "Generated" / "Identity.g.cs"
    generated.parent.mkdir(exist_ok=True)
    text = render_identity(identity)
    if not generated.is_file() or generated.read_text(encoding="utf-8") != text:
        generated.write_text(text, encoding="utf-8")
    try:
        build_for(PROJECT, cfg, acad_version, assembly_name=identity.assembly_name)
    except BuildError as exc:
        raise ProbeBuildError(str(exc)) from exc
    dll = probe_dll(cfg, acad_version)
    if not dll.is_file():
        raise ProbeBuildError(f"build succeeded but {dll} is missing")
    return dll
